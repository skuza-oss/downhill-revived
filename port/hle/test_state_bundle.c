/* STATE bundles (state_bundle.h, finding 169): every bundle fits one datagram, the riders' full pad
   refreshes fall on different sends, and a damaged bundle is refused whole. */
#include "pad_snapshot.h"
#include "state_bundle.h"
#include "puppet_record.h"
#include "state_bundle_fixture.h"
#include <assert.h>
#include <stdio.h>

/* A record as puppet.c makes one: global id, the fixed part, then the pad update. */
static int record(uint8_t *out, int rider, PadSender *sender, const uint32_t *pad)
{
    memset(out, 0, STATE_RECORD_FIXED - 1);
    out[0] = (uint8_t)rider;
    return STATE_RECORD_FIXED - 1 + pad_snapshot_pack(sender, pad, out + STATE_RECORD_FIXED - 1);
}

/* Real bundles for the net crate's tests (state_bundle_fixture.h; finding 220): a host's tick (its
   own rider, then a computer rider) and a HOLD, made by the code the game sends with. The file must
   be what this code makes now; when it is not, the test prints the file to put there. */
static const double FIXTURE_STAMP0 = 1762950000000.0, FIXTURE_STAMP1 = 1762950000016.5;
static int fixture_bundle(int rider, double stamp, uint8_t *out)
{
    static uint8_t rec[STATE_RECORD_MAX], bundles[STATE_BUNDLE_RIDERS][STATE_BUNDLE_MAX];
    PadSender sender;
    memset(&sender, 0, sizeof sender);
    sender.count = 1, sender.period = 30;  /* not a full refresh: no pad words changed */
    uint32_t pad[PAD_WORDS] = {0};
    PuppetRecord r;
    memset(&r, 0, sizeof r);
    r.rider = (uint8_t)rider, r.ms = (int32_t)(rider * 1000 + 16);
    r.pos[0] = 1520.5f, r.pos[2] = 140, r.rot[0][0] = r.rot[1][1] = r.rot[2][2] = 1, r.vel[0] = 95, r.power = 1;
    r.node = r.next = PUPPET_LINE_NONE, r.state = 0x4ED0, r.contact[0] = r.contact[1] = 1;
    uint8_t *o = puppet_record_write(&r, rec);
    o += pad_snapshot_pack(&sender, pad, o);
    const uint8_t *recs[1] = {rec};
    int size[1] = {(int)(o - rec)}, bundle_size[STATE_BUNDLE_RIDERS];
    assert(state_bundle_pack(recs, size, 1, stamp, bundles, bundle_size) == 1);
    memcpy(out, bundles[0], bundle_size[0]);
    return bundle_size[0];
}
static int print_array(char *o, const char *name, const uint8_t *b, int n)
{
    char *s = o;
    o += sprintf(o, "static const unsigned char %s[] = {", name);
    for (int i = 0; i < n; i++) o += sprintf(o, "%s0x%02x,", i % 16 ? " " : "\n    ", b[i]);
    o += sprintf(o, "\n};\n");
    return (int)(o - s);
}
static void fixture(void)
{
    static uint8_t b0[STATE_BUNDLE_MAX], b1[STATE_BUNDLE_MAX], hold[STATE_HOLD_SIZE];
    static char text[16384];
    int n0 = fixture_bundle(0, FIXTURE_STAMP0, b0), n1 = fixture_bundle(4, FIXTURE_STAMP1, b1);
    state_hold_make(hold, FIXTURE_STAMP1, 260);
    int same = n0 == (int)sizeof STATE_BUNDLE_FIXTURE_0 && !memcmp(b0, STATE_BUNDLE_FIXTURE_0, n0) &&
               n1 == (int)sizeof STATE_BUNDLE_FIXTURE_1 && !memcmp(b1, STATE_BUNDLE_FIXTURE_1, n1) &&
               (int)sizeof STATE_HOLD_FIXTURE == STATE_HOLD_SIZE && !memcmp(hold, STATE_HOLD_FIXTURE, STATE_HOLD_SIZE) &&
               STATE_BUNDLE_FIXTURE_STAMP0 == FIXTURE_STAMP0 && STATE_BUNDLE_FIXTURE_STAMP1 == FIXTURE_STAMP1;
    if (same) return;
    char *o = text;
    o += sprintf(o, "/* Real STATE bundles as the game makes them (state_bundle_pack, puppet_record_write,\n"
                    "   pad_snapshot_pack, state_hold_make; finding 220): a host's tick, its own rider's bundle and a\n"
                    "   computer rider's, and a HOLD. Generated by test_state_bundle.c, which fails while this file is\n"
                    "   not what that code makes (it prints the new one); the net crate's tests read it\n"
                    "   (port/render/net/src/bundle.rs, sfu.rs), so the Rust side is tested on real bytes. */\n");
    o += sprintf(o, "#define STATE_BUNDLE_FIXTURE_STAMP0 %.1f\n#define STATE_BUNDLE_FIXTURE_STAMP1 %.1f\n", FIXTURE_STAMP0,
                 FIXTURE_STAMP1);
    o += print_array(o, "STATE_BUNDLE_FIXTURE_0", b0, n0);
    o += print_array(o, "STATE_BUNDLE_FIXTURE_1", b1, n1);
    o += print_array(o, "STATE_HOLD_FIXTURE", hold, STATE_HOLD_SIZE);
    printf("state_bundle_fixture.h is not what the game's code makes; put this there:\n---8<---\n%s---8<---\n", text);
    assert(!"port/hle/state_bundle_fixture.h is stale");
}

int main(void)
{
    static uint8_t rec[10][STATE_RECORD_MAX], out[STATE_BUNDLE_RIDERS][STATE_BUNDLE_MAX];
    static PadSender sender[10];
    uint32_t pad[10][PAD_WORDS] = {{0}};
    const uint8_t *recs[10];
    int size[10], bundle_size[STATE_BUNDLE_RIDERS], worst = 0, most = 0, full_ticks = 0;

    /* A host's tick: its rider and nine AI riders, each with eight pad words changing every tick
       (the measured median, finding 158), phases as hle_puppet_start sets them. */
    for (int i = 0; i < 10; i++) sender[i].count = (unsigned)(30 - 3 * i) % 30;
    for (int tick = 0; tick < 600; tick++) {
        int fulls = 0;
        for (int i = 0; i < 10; i++) {
            for (int w = 0; w < 8; w++) pad[i][w] = (uint32_t)(tick * 31 + i * 7 + w);
            size[i] = record(rec[i], i, &sender[i], pad[i]);
            recs[i] = rec[i];
            fulls += size[i] == STATE_RECORD_MAX;
        }
        assert(fulls <= 1);  /* spread: never two full refreshes in one tick */
        full_ticks += fulls;
        int bundles = state_bundle_pack(recs, size, 10, 1.7e12 + tick, out, bundle_size);
        int riders = 0;
        for (int b = 0; b < bundles; b++) {
            double stamp;
            assert(bundle_size[b] <= STATE_BUNDLE_MAX && out[b][1] == b);
            assert(state_bundle_check(out[b], bundle_size[b], &stamp) == out[b][2] && stamp == 1.7e12 + tick);
            riders += out[b][2];
            if (bundle_size[b] > worst) worst = bundle_size[b];
        }
        assert(riders == 10);
        if (bundles > most) most = bundles;
    }
    assert(full_ticks == 200);  /* each rider once in 30 sends */
    assert(most <= 3);
    printf("state bundles: 10 riders a tick in at most %d bundles, largest %d of %d bytes\n", most, worst,
           STATE_BUNDLE_MAX);

    {   /* the whole budget: 2 + 8 bytes of frame and race marker, then the payload */
        assert(STATE_BUNDLE_MAX + 2 + 8 == STATE_WIRE_BUDGET && STATE_WIRE_BUDGET <= 1150 - 48 - 40);
    }
    {   /* a damaged bundle is refused before any record is read */
        double stamp;
        size[0] = record(rec[0], 3, &sender[0], pad[0]);
        int n = state_bundle_pack(recs, size, 1, 5.0, out, bundle_size);
        assert(n == 1 && state_bundle_check(out[0], bundle_size[0], &stamp) == 1);
        assert(!state_bundle_check(out[0], bundle_size[0] - 1, &stamp));    /* cut short */
        out[0][2] = 2;
        assert(!state_bundle_check(out[0], bundle_size[0], &stamp));        /* wrong count */
        out[0][2] = 1, out[0][0] = 5;
        assert(!state_bundle_check(out[0], bundle_size[0], &stamp));        /* an older version */
        out[0][0] = STATE_BUNDLE_VERSION, out[0][STATE_BUNDLE_HEADER + STATE_RECORD_FIXED - 1] = 200;
        assert(!state_bundle_check(out[0], bundle_size[0], &stamp));        /* a pad count past 146 */
    }
    /* HOLD (finding 202): its own version and index; a game that knows only bundles drops it */
    {
        uint8_t hold[STATE_HOLD_SIZE];
        double stamp = 0, last = 1762000000123.5, quiet = 0;
        assert(state_hold_make(hold, last, 260.4) == STATE_HOLD_SIZE && state_hold_check(hold, STATE_HOLD_SIZE, &stamp, &quiet) &&
               stamp == last && quiet == 260);
        assert(!state_bundle_check(hold, STATE_HOLD_SIZE, &stamp));         /* not a bundle */
        assert(!state_hold_check(hold, STATE_HOLD_SIZE - 1, &stamp, &quiet)); /* cut short */
        assert(state_hold_make(hold, last, 1e9) && state_hold_check(hold, STATE_HOLD_SIZE, &stamp, &quiet) && quiet == 65535);
        hold[1] = 0;
        assert(!state_hold_check(hold, STATE_HOLD_SIZE, &stamp, &quiet));   /* a bundle's index */
        assert(STATE_HOLD_INDEX < STATE_BUNDLE_RIDERS && STATE_HOLD_INDEX >= 3);  /* taken, and past a tick's bundles */
    }
    fixture();
    puts("state bundles: OK");
    return 0;
}
