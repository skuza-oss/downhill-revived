"""Generate the browser's shared net.h ABI offsets. Run after changing net.h."""
import ctypes as c
import json
import re
from pathlib import Path
root = Path(__file__).resolve().parents[2]
text = re.sub(r'/\*.*?\*/', '', (root / 'port/net/net.h').read_text(), flags=re.S)
max_slots = int(re.search(r'NET_MAX_SLOTS\s*=\s*(\d+)', text).group(1))
types = {'int': c.c_int32, 'unsigned': c.c_uint32, 'long long': c.c_int64,
         'uint32_t': c.c_uint32, 'double': c.c_double, 'char': c.c_char, 'unsigned char': c.c_ubyte}
layout = {}
for body, name in re.findall(r'typedef struct\s*{(.*?)}\s*(\w+);', text, flags=re.S):
    if name not in ('NetMember','NetRacer','NetResult','NetLobby','NetLobbyInfo'):
        continue
    fields = []
    for decl in body.split(';'):
        decl = decl.strip()
        if not decl: continue
        m = re.match(r'(long long|unsigned char|\w+)\s+(.+)', decl, flags=re.S)
        typ, rest = m.groups()
        for field in rest.split(','):
            m = re.fullmatch(r'\s*(\w+)(?:\[(\w+)\])?\s*', field)
            key, count = m.groups()
            t = types[typ]
            if count: t = t * (max_slots if count == 'NET_MAX_SLOTS' else int(count))
            fields.append((key,t))
    cls = type(name,(c.Structure,),{'_fields_':fields})
    types[name] = cls
    layout[name] = {'size': c.sizeof(cls), **{key:[getattr(cls,key).offset,c.sizeof(t)] for key,t in fields}}
output = '// Generated by port/tools/gen_net_layout.py from net.h.\nexport const layout = '+json.dumps(layout,indent=2)+';\n'
import sys
target = root/'port/web/www/net_layout.js'
if '--check' in sys.argv:
    assert target.read_text() == output, 'run gen_net_layout.py'
    import subprocess, shutil
    clang = shutil.which('clang') or str(Path.home()/'scoop/apps/llvm/current/bin/clang.exe')
    checks = '#include "port/net/net.h"\n#include <stddef.h>\n'
    for name, fields in layout.items():
        checks += '_Static_assert(sizeof(%s)==%d,"size");\n' % (name, fields['size'])
        for key, field in fields.items():
            if key != 'size':
                checks += '_Static_assert(offsetof(%s,%s)==%d,"offset");\n' % (name,key,field[0])
    for triple in ['wasm32','x86_64-pc-windows-msvc','x86_64-unknown-linux-gnu','aarch64-apple-darwin']:
        subprocess.run([clang,'-target',triple,'-ffreestanding','-std=c11','-fsyntax-only','-I',str(root),'-x','c','-'],input=checks,text=True,check=True)
    print('net ABI: four targets passed')
else:
    target.write_text(output)
