"""The code and data identity tables of dhd_core.wasm (finding 081, the code pointers of the state
trace).

A guest word that holds a code address names a function, and the address moves whenever the code
before it changes. The state trace (port/hle/state_trace.c) therefore hashes such a word by
identity: the function that contains the address, a stable 32-bit id of the function's name, and
the offset inside the function. build_wasm.py writes this table after a link, compiles it into the
module, and links again until the table it writes is the one it linked (wasm_link).

Table: one row {start, size, id} per symbol, sorted by start. id is FNV-1a of the symbol's name
(with a leading '_', the C name the state traces have always used), so the same name gives the
same id in every build. Code rows are the module's function-table entries (a code address in
wasm is a table index); data rows are the named linear-memory objects of wasm-ld's map.
"""
import re


def fnv1a(name):
    h = 0x811C9DC5
    for b in name.encode('ascii'):
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def wasm_code_rows(path):
    """Trace rows for table-0 function pointers, from this module's own names.

    Names carry the '_' of the C names the traces have always used. Address-only ABI thunks
    represent their target's identity, as wasm_postlink's shadow tables do.
    Slot zero is the null pointer and must never acquire a function identity.
    """
    from pathlib import Path
    from wasm_postlink import Module, THUNK
    module = Module(Path(path).read_bytes())
    return [(index, 1, '_' + THUNK.sub(r'\1', module.name(function)))
            for index, function in enumerate(module.table_entries())
            if index and function is not None]


def wasm_fixup_source(path):
    """Pointer-word provenance from build_wasm's generated fixup initializers.

    A scalar absolute relocation (for example D_52 = 82) is not a code
    pointer even when its value happens to be a valid table index.
    """
    from pathlib import Path
    text = Path(path).read_text(encoding='utf-8')
    rows = re.findall(r'\{0x([0-9A-Fa-f]+)U, \(unsigned\)\(uintptr_t\)&\w+\}', text)
    addresses = sorted({int(address, 16) for address in rows})
    if not addresses:
        raise ValueError('no function-valued wasm fixups found')
    return ('\nconst uint32_t dhd_code_fixup_count = %d;\n'
            'const uint32_t dhd_code_fixups[] = {%s};\n' %
            (len(addresses), ','.join('0x%Xu' % address for address in addresses)))


def wasm_data_rows(map_path):
    """Named linear-memory objects from wasm-ld --Map, with '_'-prefixed C names.

    Code pointers can carry module data as their context (SIF pending jobs,
    for example). Compare that context by symbol/offset. Ignore section/segment
    rows and compiler .L temporaries.
    """
    rows = []
    with open(map_path, encoding='utf-8') as source:
        for line in source:
            fields = line.split()
            if len(fields) != 4 or not re.fullmatch(r'[0-9A-Fa-f]+',fields[0]):
                continue
            address, _, size, name = fields
            if not re.fullmatch(r'[0-9A-Fa-f]+',size): continue
            address, size = int(address,16), int(size,16)
            if address < 0x70100000 or not size or name.startswith(('.', '@')) or any(c in name for c in '/\\:('):
                continue
            rows.append((address,size,'_'+name))
    return dedupe(rows)


def dedupe(table):
    table.sort(key=lambda e: (e[0], e[2]))
    rows = []
    for start, length, name in table:  # symbols at one address (aliases, folded code): the smallest name
        if rows and rows[-1][0] == start:
            continue
        rows.append((start, length, name))
    return rows


def write_table(code_rows, data_rows, out_path, wasm_fixups=None):
    """The C file of the tables: rows of (start, length, name) for the code symbols (dhd_code_table)
    and the data symbols (dhd_data_table). With no rows it's the empty table (the first link, which
    must define the symbols). wasm_fixups is wasm_fixup_source's text; without it the module gets
    the empty fixup list (state_trace.c reads it)."""
    lines = ['/* Generated by port/tools/codeids.py at link time: the code and data symbols of dhd.exe. */',
             '#include <stdint.h>']
    for label, rows in (('code', code_rows), ('data', data_rows)):
        lines.append('const uint32_t dhd_%s_count = %d;' % (label, len(rows)))
        lines.append('const uint32_t dhd_%s_table[%d][3] = {' % (label, max(1, len(rows))))
        for start, length, name in rows:
            lines.append('{0x%08X, 0x%X, 0x%08X}, /* %s */' % (start, length, fnv1a(name), name.replace('*/', '* /')))
        if not rows:
            lines.append('{0, 0, 0}')
        lines.append('};')
    lines += ['#ifdef __wasm__',
              (wasm_fixups or 'const uint32_t dhd_code_fixup_count = 0;\nconst uint32_t dhd_code_fixups[1] = {0};').strip(),
              '#endif']
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
