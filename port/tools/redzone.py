#!/usr/bin/env python3
"""Red zones around the game's address-taken locals: a test build only (DHD_CORE_REDZONE=1,
build_wasm.py; finding 213, the class of findings 094 and 207).

The retail code sometimes writes past a local into the one the EE frame puts after it; in the port
clang lays locals out as it likes, so such a write lands on something else. In this build mode each
game function's address-taken locals move into one struct, in declaration order, with a 16-byte red
zone before, between and after them, filled with 0xCD on entry and checked when the function's scope
ends (a `cleanup` variable, so every return path); a changed byte is reported once per function and
local on stderr (dhd.log):

    redzone: func_0019E550: 16 of 16 bytes after sp60 (16 bytes) written

Each value keeps the port's 16-byte alignment of locals (build_wasm.align_aggregate_allocas), so a
quadword access behaves as in the players' build. The rewrite works on the unit's final text with
clang's own AST (declaration and reference offsets, macro arguments included), so it needs no
other parser. Locals it leaves alone (counted per unit): with an initializer, static, of a variably
modified or unnamed type, or referenced inside a macro's body.

usage (a test of the rewrite, no build): python port/tools/redzone.py FILE.c FUNCTION.json"""
import json, re

RZ = 16
PRELUDE = ('%sextern void dhd_rz_enter(void *);\n'
           '%sextern void dhd_rz_leave(void *);\n')

# The frame starts with its own description (no static data: the C++ symbol policy of
# wasm_retail_names.py renames function-local statics): the function's name, the locals' names
# (NUL-separated), their count, the red zones' offsets (count + 1), the locals' sizes.
RUNTIME = r'''/* Generated by build_wasm.py for DHD_CORE_REDZONE=1 (port/tools/redzone.py, finding 213):
   a test build only. dhd_rz_enter copies each frame's description into a table keyed by the
   frame's address, so a write that reaches the description in the frame is itself reported. */
#include <stdio.h>
#include <string.h>
#define SLOTS 1024
#define MAXN 32
struct head { const char *func; const char *names; int n; unsigned offs[1]; };
struct live { void *frame; const char *func; const char *names; int n; unsigned offs[MAXN + 1]; unsigned sizes[MAXN]; };
static struct live table[SLOTS];
static const char *seen[4096];
static unsigned seen_k[4096];

static unsigned slot_of(void *frame)
{
    return (unsigned)(((unsigned long)frame >> 4) * 2654435761u) % SLOTS;
}

void dhd_rz_enter(void *frame)
{
    struct head *h = (struct head *)frame;
    unsigned at = slot_of(frame), i;
    int k;
    for (i = 0; i < SLOTS && table[at].frame && table[at].frame != frame; i++)
        at = (at + 1) % SLOTS;
    if (i == SLOTS || h->n > MAXN)
        return; /* table full: this frame goes unchecked */
    table[at].frame = frame;
    table[at].func = h->func;
    table[at].names = h->names;
    table[at].n = h->n;
    memcpy(table[at].offs, h->offs, (h->n + 1) * sizeof(unsigned));
    memcpy(table[at].sizes, h->offs + h->n + 1, h->n * sizeof(unsigned));
    for (k = 0; k <= h->n; k++)
        memset((unsigned char *)frame + h->offs[k], 0xCD, 16);
}

static int first_time(const char *func, unsigned k)
{
    unsigned i, at = (unsigned)(((unsigned long)func / 4) * 31 + k) % 4096;
    for (i = 0; i < 4096; i++, at = (at + 1) % 4096) {
        if (seen[at] == func && seen_k[at] == k)
            return 0;
        if (!seen[at]) {
            seen[at] = func;
            seen_k[at] = k;
            return 1;
        }
    }
    return 0;
}

static const char *name_of(const char *names, int k)
{
    while (k-- > 0)
        names += strlen(names) + 1;
    return names;
}

static void report(const struct live *l, int k, int lo, int hi)
{
    if (!first_time(l->func, (unsigned)k))
        return;
    if (k < 0)
        fprintf(stderr, "redzone: %s: the frame's description (before the red zone before %s) written\n", l->func,
                name_of(l->names, 0));
    else if (k == 0)
        fprintf(stderr, "redzone: %s: bytes %d..%d of the 16 before %s (%u bytes) written\n", l->func, lo, hi,
                name_of(l->names, 0), l->sizes[0]);
    else
        fprintf(stderr, "redzone: %s: bytes %d..%d of the 16 after %s (%u bytes) written\n", l->func, lo, hi,
                name_of(l->names, k - 1), l->sizes[k - 1]);
    fflush(stderr);
}

/* The leaving frame: its description from the table, its red zones checked, its entry removed. */
void dhd_rz_leave(void *frame)
{
    struct head *h = (struct head *)frame;
    unsigned at = slot_of(frame), i;
    struct live *l;
    int k, j, lo, hi;
    for (i = 0; i < SLOTS && table[at].frame != frame; i++) {
        if (!table[at].frame)
            return;
        at = (at + 1) % SLOTS;
    }
    if (i == SLOTS)
        return;
    l = &table[at];
    if (h->func != l->func || h->names != l->names || h->n != l->n ||
        memcmp(h->offs, l->offs, (l->n + 1) * sizeof(unsigned)))
        report(l, -1, 0, 0);
    for (k = 0; k <= l->n; k++) {
        unsigned char *z = (unsigned char *)frame + l->offs[k];
        lo = -1;
        hi = -1;
        for (j = 0; j < 16; j++)
            if (z[j] != 0xCD) {
                if (lo < 0)
                    lo = j;
                hi = j;
            }
        if (lo >= 0)
            report(l, k, lo, hi);
    }
    /* remove it, keeping the probe chains of the open addressing intact */
    l->frame = 0;
    for (at = (at + 1) % SLOTS; table[at].frame; at = (at + 1) % SLOTS) {
        struct live moved = table[at];
        unsigned home = slot_of(moved.frame);
        table[at].frame = 0;
        while (table[home].frame)
            home = (home + 1) % SLOTS;
        table[home] = moved;
    }
}
'''


def decode_all(text):
    d, i, out = json.JSONDecoder(), 0, []
    while i < len(text):
        while i < len(text) and text[i].isspace():
            i += 1
        if i >= len(text):
            break
        o, i = d.raw_decode(text, i)
        out.append(o)
    return out


def walk(node, parents=()):
    if isinstance(node, dict):
        yield node, parents
        for k, v in node.items():
            if k in ('inner', 'init'):
                for x in (v if isinstance(v, list) else [v]):
                    yield from walk(x, parents + (node,))
    elif isinstance(node, list):
        for x in node:
            yield from walk(x, parents)


def ref_offset(loc):
    """The main file's offset of a reference, or None (inside a macro body, another file)."""
    if 'spellingLoc' in loc:
        if not loc.get('expansionLoc', {}).get('isMacroArgExpansion'):
            return None
        loc = loc['spellingLoc']
    if 'includedFrom' in loc or 'offset' not in loc:
        return None
    return loc['offset'], loc.get('tokLen')


ADDRESS_PATH = ('MemberExpr', 'ArraySubscriptExpr', 'ParenExpr', 'ImplicitCastExpr', 'CStyleCastExpr')


def address_taken(parents):
    """A DeclRefExpr whose object's address is taken: under &, or an array that decays."""
    for p in reversed(parents):
        k = p.get('kind')
        if k == 'UnaryOperator' and p.get('opcode') == '&':
            return True
        if k == 'ImplicitCastExpr' and p.get('castKind') == 'ArrayToPointerDecay':
            return True
        if k == 'ArraySubscriptExpr':
            return False  # a[i] reads or writes an element in place
        if k not in ADDRESS_PATH:
            return False
    return False


def uses(text, lo, hi, name):
    """Offsets of name as a whole word in text[lo:hi], not as a member (.name, ->name)."""
    return [m.start() for m in re.finditer(r'(?<![\w.>])%s(?!\w)' % re.escape(name), text[lo:hi])
            if not text[lo + m.start() - 2:lo + m.start()].endswith('->')]


def default_construct(v):
    """A C++ local declared without an initializer: its default constructor, no arguments."""
    inner = v.get('inner') or []
    return (v.get('init') == 'call' and len(inner) == 1 and inner[0].get('kind') == 'CXXConstructExpr'
            and not inner[0].get('inner'))


def plan_function(fn, text):
    """(insert offset, struct text, edits [(offset, length, new)], names, skipped) for one function."""
    body = next((x for x in fn.get('inner', []) if x.get('kind') == 'CompoundStmt'), None)
    if body is None or 'offset' not in body['range']['begin']:
        return None
    decls, refs, taken = {}, {}, set()
    for node, parents in walk(body):
        k = node.get('kind')
        if k == 'VarDecl':
            decls.setdefault(node['name'], []).append(node)
        elif k == 'DeclRefExpr':
            r = node.get('referencedDecl', {})
            if r.get('kind') == 'VarDecl':
                refs.setdefault(r['id'], []).append(node)
                if address_taken(parents):
                    taken.add(r['id'])
    chosen, skipped = [], []
    for name, vs in decls.items():
        for v in vs:
            if v['id'] not in taken:
                continue
            qt = v.get('type', {}).get('qualType', '')
            why = None
            if len(vs) > 1:
                why = 'declared twice'
            elif (('init' in v and not default_construct(v)) or
                  v.get('storageClass') in ('static', 'extern', 'register')):
                why = 'initializer or storage class'
            elif re.search(r'unnamed|anonymous|lambda|\[\*\]|\(\*\)\[|\bauto\b', qt) or \
                    re.search(r'\[[^\]0-9 ]', qt):
                why = 'type'
            elif 'offset' not in v.get('loc', {}):
                why = 'declared in a macro'
            else:
                lo, hi = body['range']['begin']['offset'], body['range']['end'].get('offset', len(text))
                offs = [ref_offset(r['range']['begin']) for r in refs.get(v['id'], [])]
                # each reference must be the name itself, in this function's body (a nested macro's
                # argument can be spelled in a #define elsewhere in the unit)
                if any(o is None or not lo < o[0] < hi or text[o[0]:o[0] + len(name)] != name for o in offs):
                    why = 'used in a macro body'
                elif len(uses(text, lo, hi, name)) != len({o[0] for o in offs}) + 1:
                    why = 'used where the AST has no reference (an unevaluated operand)'
            if why:
                skipped.append((name, why))
            else:
                chosen.append(v)
    chosen = chosen[:32]  # the runtime's limit per frame (MAXN)
    if not chosen:
        return None if not skipped else (None, None, [], [], skipped)
    chosen.sort(key=lambda v: v['loc']['offset'])
    edits = []
    members = [None, 'char rz0[%d];' % RZ]
    names = []
    for i, v in enumerate(chosen):
        qt = v['type']['qualType']
        members.append('__typeof__(%s) v%d __attribute__((aligned(16)));' % (qt, i))
        members.append('char rz%d[%d];' % (i + 1, RZ))
        names.append(v['name'])
        # the declaration's name becomes an unused one; every reference names the member
        o = v['loc']['offset']
        edits.append((o, len(v['name']), v['name'] + '__rz_unused'))
        for r in refs.get(v['id'], []):
            o, n = ref_offset(r['range']['begin'])
            edits.append((o, n, '(dhd_rz_frame.v%d)' % i))
    fname = fn.get('name', '?')
    n = len(chosen)
    head = ['const char *rz_func;', 'const char *rz_names;', 'int rz_n;', 'unsigned rz_offs[%d];' % (n + 1),
            'unsigned rz_sizes[%d];' % n]
    fill = ['dhd_rz_frame.rz_func = "%s";' % fname,
            'dhd_rz_frame.rz_names = "%s";' % '\\0'.join(names),  # C's "\0" between them
            'dhd_rz_frame.rz_n = %d;' % n]
    fill += ['dhd_rz_frame.rz_offs[%d] = __builtin_offsetof(struct dhd_rz_t, rz%d);' % (k, k) for k in range(n + 1)]
    fill += ['dhd_rz_frame.rz_sizes[%d] = sizeof(dhd_rz_frame.v%d);' % (k, k) for k in range(n)]
    struct = ('struct dhd_rz_t { %s %s } __attribute__((aligned(16))) dhd_rz_frame __attribute__((cleanup(dhd_rz_leave))); '
              '%s dhd_rz_enter(&dhd_rz_frame);' % (' '.join(head), ' '.join(members[1:]), ' '.join(fill)))
    return body['range']['begin']['offset'] + 1, struct, edits, names, skipped


FUNCTION_KINDS = ('FunctionDecl', 'CXXMethodDecl', 'CXXConstructorDecl', 'CXXDestructorDecl')


def main_file_functions(nodes, text):
    """Function definitions of the unit's own text (not its headers): a body that starts with '{'
    at its offset in text, and the name at the declaration's offset."""
    out = []
    stack = list(nodes)
    while stack:
        n = stack.pop()
        if not isinstance(n, dict):
            continue
        k = n.get('kind')
        if k in FUNCTION_KINDS:
            body = next((x for x in n.get('inner', []) if x.get('kind') == 'CompoundStmt'), None)
            b = body and body['range']['begin'].get('offset')
            o = n.get('loc', {}).get('offset')
            name = n.get('name', '')
            if b is not None and o is not None and text[b:b + 1] == '{' and text[o:o + len(name)] == name:
                out.append(n)
            continue
        if k in ('TranslationUnitDecl', 'LinkageSpecDecl', 'NamespaceDecl', 'CXXRecordDecl'):
            stack.extend(n.get('inner', []))
    return out


def instrument(text, functions, cpp):
    """text with every function of `functions` (AST JSON objects: function definitions, or the
    whole translation unit) instrumented; (text, report)."""
    inserts, edits, report = [], [], {'functions': 0, 'locals': 0, 'skipped': []}
    done = set()
    for fn in main_file_functions(functions, text):
        plan = plan_function(fn, text)
        if not plan:
            continue
        at, struct, ed, names, skipped = plan
        report['skipped'] += [(fn.get('name'), n, w) for n, w in skipped]
        if at is None or at in done:
            continue
        done.add(at)
        inserts.append((at, 0, ' ' + struct + ' '))
        edits += ed
        report['functions'] += 1
        report['locals'] += len(names)
    if not inserts:
        return text, report
    out = text
    # a macro argument used twice in the macro's body is one reference in the text
    for o, n, new in sorted(set(inserts + edits), key=lambda e: -e[0]):
        out = out[:o] + new + out[o + n:]
    ext = 'extern "C" ' if cpp else ''
    first = out.find('\n#line ')
    prelude = PRELUDE % (ext, ext)
    out = out[:first + 1] + prelude + out[first + 1:] if first >= 0 else prelude + out
    return out, report


def instrument_bytes(text, functions, cpp):
    """As instrument(), with clang's byte offsets on a str whose characters may be multi-byte."""
    raw = text.encode('utf-8', 'surrogateescape')
    if len(raw) == len(text):
        return instrument(text, functions, cpp)
    s = raw.decode('latin-1')
    out, report = instrument(s, functions, cpp)
    return out.encode('latin-1').decode('utf-8', 'surrogateescape'), report


if __name__ == '__main__':
    import sys
    src = open(sys.argv[1], encoding='utf-8', errors='surrogateescape').read()
    fns = decode_all(open(sys.argv[2]).read())
    out, rep = instrument_bytes(src, fns, sys.argv[1].endswith('.cpp'))
    sys.stdout.write(out)
    sys.stderr.write(json.dumps(rep) + '\n')
