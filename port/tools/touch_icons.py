#!/usr/bin/env python3
"""The touch controls' action pictures (finding 229): port/render/src/present/touch_icons.txt (the
shapes, written by hand) into port/render/src/present/touch_icons.wgsl (the overlay's shader draws
them as signed distances), and preview sheets of them.

    python port/tools/touch_icons.py               # write touch_icons.wgsl
    python port/tools/touch_icons.py --check       # fail if touch_icons.wgsl is not what the shapes give
    python port/tools/touch_icons.py --sheet OUT.png [--px N ...]   # the pictures at N pixels a picture
                                                    # (numpy and Pillow; the same distances as the shader)
"""
import argparse
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'port', 'render', 'src', 'present', 'touch_icons.txt')
OUT = os.path.join(ROOT, 'port', 'render', 'src', 'present', 'touch_icons.wgsl')

ARGS = {'seg': 5, 'disc': 3, 'ring': 4, 'arc': 6, 'box': 5}


def parse(path=SRC):
    """[(name, [(cut, gap, kind, numbers)])] in the file's order."""
    icons = []
    gap = 0.0
    with open(path, encoding='utf-8') as f:
        for n, raw in enumerate(f, 1):
            line = raw.split('#', 1)[0].split()
            if not line:
                continue
            where = f'{os.path.basename(path)}:{n}'
            if line[0] == 'icon':
                if len(line) != 2:
                    raise SystemExit(f'{where}: icon NAME')
                icons.append((line[1], []))
                gap = 0.0
                continue
            if not icons:
                raise SystemExit(f'{where}: a shape before the first icon')
            if line[0] == 'gap':
                gap = float(line[1])
                continue
            cut = line[0] == 'cut'
            if cut:
                line = line[1:]
            kind, nums = line[0], [float(v) for v in line[1:]]
            if kind == 'poly':
                if len(nums) < 7 or len(nums) % 2 == 0:
                    raise SystemExit(f'{where}: poly w x0 y0 x1 y1 x2 y2 ...')
            elif ARGS.get(kind) != len(nums):
                raise SystemExit(f'{where}: {kind} takes {ARGS.get(kind)} numbers')
            if any(abs(v) > 1.5 for v in nums) and kind != 'arc':
                raise SystemExit(f'{where}: a number outside the picture')
            icons[-1][1].append((cut, gap, kind, nums))
    return icons


def f(v):
    s = f'{v:.4f}'.rstrip('0')
    return s + '0' if s.endswith('.') else s


def vec(x, y):
    return f'vec2f({f(x)}, {f(y)})'


def wgsl_shape(kind, n):
    """The WGSL expression of one shape's distance at p."""
    if kind == 'seg':
        return f'ic_seg(p, {vec(n[0], n[1])}, {vec(n[2], n[3])}) - {f(n[4] / 2)}'
    if kind == 'disc':
        return f'length(p - {vec(n[0], n[1])}) - {f(n[2])}'
    if kind == 'ring':
        return f'abs(length(p - {vec(n[0], n[1])}) - {f(n[2])}) - {f(n[3] / 2)}'
    if kind == 'arc':
        a0, a1 = math.radians(n[3]), math.radians(n[4])
        return f'ic_arc(p, {vec(n[0], n[1])}, {f(n[2])}, {f(a0)}, {f(a1)}) - {f(n[5] / 2)}'
    if kind == 'box':
        return f'ic_box(p - {vec(n[0], n[1])}, {vec(n[2], n[3])}, {f(n[4])})'
    raise AssertionError(kind)


def wgsl(icons):
    out = ['// Generated by port/tools/touch_icons.py from touch_icons.txt (finding 229): the touch controls\'',
           '// action pictures, original work for this project (GPL-3.0-or-later). Edit the .txt and run the',
           '// tool; do not edit this file. p is in the picture\'s box (-1..1, y down); <= 0 is inside.',
           '']
    for i, (name, shapes) in enumerate(icons):
        out.append(f'fn icon_{name}(p: vec2f) -> f32 {{')
        out.append('    var d = 1e9;')
        for cut, gap, kind, n in shapes:
            if kind == 'poly':
                pts = [(n[k], n[k + 1]) for k in range(1, len(n), 2)]
                out.append('    {')
                out.append(f'        var e = dot(p - {vec(*pts[0])}, p - {vec(*pts[0])}); var s = 1.0;')
                for k in range(len(pts)):
                    a, b = pts[k], pts[k - 1]
                    out.append(f'        ic_edge(p, {vec(*a)}, {vec(*b)}, &e, &s);')
                expr = f's * sqrt(e) - {f(n[0] / 2)}'
                if cut:
                    out.append(f'        d = max(d, -({expr} - {f(gap)}));')
                else:
                    out.append(f'        d = min(d, {expr});')
                out.append('    }')
                continue
            expr = wgsl_shape(kind, n)
            out.append(f'    d = max(d, -({expr} - {f(gap)}));' if cut else f'    d = min(d, {expr});')
        out.append('    return d;')
        out.append('}')
        out.append('')
    out.append('fn icon_dist(id: i32, p: vec2f) -> f32 {')
    out.append('    switch id {')
    for i, (name, _) in enumerate(icons):
        out.append(f'        case {i}: {{ return icon_{name}(p); }}')
    out.append('        default: { return 1e9; }')
    out.append('    }')
    out.append('}')
    return '\n'.join(out) + '\n'


# ---------------------------------------------------------------- the same distances in numpy

def dist(icon, X, Y):
    import numpy as np

    def seg(ax, ay, bx, by):
        px, py, ex, ey = X - ax, Y - ay, bx - ax, by - ay
        h = np.clip((px * ex + py * ey) / max(ex * ex + ey * ey, 1e-12), 0, 1)
        return np.hypot(px - ex * h, py - ey * h)

    def shape(kind, n):
        if kind == 'seg':
            return seg(*n[:4]) - n[4] / 2
        if kind == 'disc':
            return np.hypot(X - n[0], Y - n[1]) - n[2]
        if kind == 'ring':
            return abs(np.hypot(X - n[0], Y - n[1]) - n[2]) - n[3] / 2
        if kind == 'arc':
            cx, cy, r = n[0], n[1], n[2]
            a0, a1 = math.radians(n[3]), math.radians(n[4])
            mid, half = (a0 + a1) / 2, (a1 - a0) / 2
            ang = np.arctan2(-(Y - cy), X - cx)
            off = np.abs(np.arctan2(np.sin(ang - mid), np.cos(ang - mid)))
            on = np.abs(np.hypot(X - cx, Y - cy) - r)
            e0 = np.hypot(X - (cx + r * math.cos(a0)), Y - (cy - r * math.sin(a0)))
            e1 = np.hypot(X - (cx + r * math.cos(a1)), Y - (cy - r * math.sin(a1)))
            return np.where(off <= half, on, np.minimum(e0, e1)) - n[5] / 2
        if kind == 'box':
            qx = np.abs(X - n[0]) - n[2] + n[4]
            qy = np.abs(Y - n[1]) - n[3] + n[4]
            return np.hypot(np.maximum(qx, 0), np.maximum(qy, 0)) + np.minimum(np.maximum(qx, qy), 0) - n[4]
        if kind == 'poly':
            pts = [(n[k], n[k + 1]) for k in range(1, len(n), 2)]
            e = (X - pts[0][0]) ** 2 + (Y - pts[0][1]) ** 2
            s = np.ones_like(X)
            for k in range(len(pts)):
                (vx, vy), (wx, wy) = pts[k], pts[k - 1]
                ex, ey = wx - vx, wy - vy
                px, py = X - vx, Y - vy
                h = np.clip((px * ex + py * ey) / (ex * ex + ey * ey), 0, 1)
                e = np.minimum(e, (px - ex * h) ** 2 + (py - ey * h) ** 2)
                c1, c2, c3 = Y >= vy, Y < wy, ex * py > ey * px
                flip = (c1 & c2 & c3) | (~c1 & ~c2 & ~c3)
                s = np.where(flip, -s, s)
            return s * np.sqrt(e) - n[0] / 2
        raise AssertionError(kind)

    d = np.full_like(X, 1e9)
    for cut, gap, kind, n in icon[1]:
        v = shape(kind, n)
        d = np.maximum(d, -(v - gap)) if cut else np.minimum(d, v)
    return d


def render(icon, px, mirror=False):
    """An RGBA picture px wide: white glyph with the shader's dark edge, on transparent."""
    import numpy as np
    g = (np.arange(px) + 0.5) / px * 2 - 1
    X, Y = np.meshgrid(g, g)
    if mirror:
        X = -X
    d = dist(icon, X, Y)
    aa = 2.0 / px
    edge = max(0.09, aa * 1.2)
    on = np.clip(0.5 - d / aa, 0, 1)
    halo = np.clip(0.5 - (d - edge) / aa, 0, 1) * 0.6
    a = on + halo * (1 - on)
    rgb = np.where(a > 0, on / np.maximum(a, 1e-6), 0) * 255
    out = np.zeros((px, px, 4), np.uint8)
    out[..., 0] = out[..., 1] = out[..., 2] = rgb.astype(np.uint8)
    out[..., 3] = (a * 255).astype(np.uint8)
    return out


def sheet(icons, path, sizes):
    from PIL import Image, ImageDraw
    pad = 8
    w = sum(max(sizes) + pad for _ in icons) + pad
    h = sum(s + pad for s in sizes) + pad + 14
    img = Image.new('RGBA', (w, h), (120, 128, 136, 255))
    dr = ImageDraw.Draw(img)
    for i, icon in enumerate(icons):
        x = pad + i * (max(sizes) + pad)
        dr.text((x, 2), icon[0], fill=(255, 255, 255, 255))
        y = 16
        for s in sizes:
            dr.ellipse((x - 1, y - 1, x + s, y + s), fill=(10, 14, 18, 150), outline=(255, 255, 255, 220))
            g = Image.fromarray(render(icon, int(s * 0.62)))
            img.alpha_composite(g, (x + (s - g.width) // 2, y + (s - g.height) // 2))
            y += s + pad
    img.save(path)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--sheet')
    ap.add_argument('--px', type=int, nargs='*', default=[160, 64, 40, 28])
    a = ap.parse_args()
    icons = parse()
    text = wgsl(icons)
    if a.sheet:
        sheet(icons, a.sheet, a.px)
        print('sheet', a.sheet)
        return 0
    if a.check:
        with open(OUT, encoding='utf-8', newline='') as fh:
            if fh.read() != text:
                print('ERROR port/render/src/present/touch_icons.wgsl: not what touch_icons.txt gives; run python port/tools/touch_icons.py')
                return 1
        print('touch_icons: OK')
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print('wrote', os.path.relpath(OUT, ROOT), f'({len(icons)} pictures)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
